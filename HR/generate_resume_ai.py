def generate_resume(title, company, location=''):
    prompt = RESUME_PROMPT_TPL.format(title=title, company=company, location=location)
    text = ask(prompt, system=RESUME_SYSTEM, max_tokens=2048, temperature=0.5)
    return text

if __name__ == '__main__':
    if len(sys.argv) < 3:
        print(json.dumps({'error': 'Usage: generate_resume_ai.py <title_b64> <company_b64> [location_b64]'}))
        sys.exit(1)
    import base64
    title = base64.b64decode(sys.argv[1]).decode('utf-8') if sys.argv[1] else ''
    raw_c = base64.b64decode(sys.argv[2]).decode('utf-8') if sys.argv[2] else ''
    company = '' if raw_c == '_unknown' else raw_c
    location = base64.b64decode(sys.argv[3]).decode('utf-8') if len(sys.argv) > 3 and sys.argv[3] and sys.argv[3] != 'Xw' else ''
    try:
        text = generate_resume(title, company, location)
        print(json.dumps({'text': text}, ensure_ascii=False))
    except Exception as e:
        print(json.dumps({'error': str(e)}, ensure_ascii=False))
        sys.exit(1)
