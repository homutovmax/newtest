def seed_from(s):
    return int(hashlib.md5(s.encode("utf-8")).hexdigest()[:8], 16)


def pick(arr, seed, n=1):
    if not arr:
        return []
    if n == 1:
        return arr[seed % len(arr)]
    return [arr[(seed + i) % len(arr)] for i in range(n)]


