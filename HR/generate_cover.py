def generate_letter(title, company, scenario=0, salary="", location=""):
    s = seed_from(title + company + str(scenario))
    cat = classify_title(title)
    if scenario == 1:
        cat = "telecom"
    elif scenario == 2:
        cat = "ai_product"
    elif scenario == 3:
        cat = "strategy"
    elif scenario == 4:
        cat = "ba"

    greeting = pick(GREETINGS, s)
    loc_str = f" ({location})" if location else ""
    intro_tpl = pick(INTROS, s + 1)
    intro = intro_tpl.format(title=title, company=company, location=loc_str)

    profiles = PROFILES.get(cat, PROFILES["telecom"])
    profile = pick(profiles, s + 2)

    exp_list = EXPERIENCES.get(cat, EXPERIENCES["telecom"])
    experience = pick(exp_list, s + 3)

    ach_list = ACHIEVEMENTS.get(cat, ACHIEVEMENTS["telecom"])
    achievements = pick(ach_list, s + 4, 3)

    closings = CLOSINGS.get(cat, CLOSINGS["telecom"])
    closing = pick(closings, s + 5)

    body = f"{profile}\n\n{experience}"
    if achievements:
        body += f"\n\nРелевантные результаты:\n" + "\n".join(achievements)

    letter = f"""{greeting}

{intro}

{body}

{closing}

С уважением,
Максим Хомутов
homutov.m@gmail.com
+7 (916) 192-88-47

Дата: {TODAY}
Вакансия: {title}
Компания: {company}
Локация: {location}"""

    return letter, cat


